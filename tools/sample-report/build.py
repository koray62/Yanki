def font_faces():
    out = []
    for w in (400, 500, 600, 700):
        for sub in ("latin", "latin-ext"):
            out.append(f"@font-face{{font-family:'Inter';font-weight:{w};src:url('file://{FONTS}/inter/files/inter-{sub}-{w}-normal.woff2') format('woff2')}}")
    return "\n".join(out)


def build(x):
    T = x["tags"]
    tag = {
        "pr": f'<span class="tag tag-pr">{ALERT.format(bg="currentColor", fg="#fff")}{T["pr"]}</span>',
        **{k: f'<span class="tag tag-{k}">{T[k]}</span>' for k in ("neg", "pos", "neu", "adv", "dis")},
    }

    def card(c):
        tone = "neg" if ("neg" in c["tags"] or "pr" in c["tags"]) else ("pos" if "pos" in c["tags"] else "neu")
        src = "".join(
            f'<div class="src"><div><b>{E(n)}</b><span class="t">{E(t)}</span></div>'
            + (f'<div class="q">“{E(q)}”</div>' if q else "")
            + f'<div class="u">{E(u)}</div></div>' for n, t, q, u in c["sources"])
        return (f'<div class="card card-{tone}{" card-pr" if "pr" in c["tags"] else ""}">'
                f'<div class="h">{"".join(tag[t] for t in c["tags"])}<span class="ttl">{E(c["title"])}</span></div>'
                f'<p class="sum">{E(c["summary"])}</p><p class="meta">{c["meta"]}</p><div class="srcs">{src}</div></div>')

    pr_rows = "".join(
        f'<div class="pr-row"><div class="pr-t">{E(p["title"])} <span class="sev">{E(p["sev"])}</span></div>'
        f'<div class="pr-m">{E(p["meta"])}</div><div class="pr-a"><b>{x["action"]}</b> {E(p["action"])}</div></div>' for p in x["pr"])
    nums = ["10", "13", "5", "3", "2", "2", "1", "2"]
    cls = ["ink", "slate", "pos", "neg", "slate", "neg pr", "adv", "dis"]
    stats = "".join(f'<div class="stat {c}"><b>{n}</b><span>{l}</span></div>' for n, l, c in zip(nums, x["stats"], cls))
    comp = "".join(
        f'<div class="comp"><div class="comp-h"><h3>{E(name)}</h3><div><span class="chip chip-adv">{T["adv"]}: {a}</span>'
        f'<span class="chip chip-dis">{T["dis"]}: {d}</span></div></div>{"".join(card(c) for c in cards)}</div>'
        for name, a, d, cards in x["comp"])
    css = open(os.path.join(HERE, "report.css"), encoding="utf-8").read()
    lg = x["legend"]
    return f'''<!doctype html><html lang="{x["lang"]}"><head><meta charset="utf-8"><title>{E(x["doc_title"])}</title>
<style>
{font_faces()}
{css}</style></head><body>
<div class="brand">YANKI</div>
<div class="top"><div><h1>{E(x["company"])}</h1><div class="sub">{E(x["sub"])}</div></div><div class="per">{x["period"]}</div></div>
<div class="prbox"><div class="prbox-h">{ALERT.format(bg="#fff", fg="#B42318")}{x["pr_head"]}</div>{pr_rows}</div>
<div class="stats">{stats}</div>
<div class="bar"><i style="width:50%;background:#1B7A43"></i><i style="width:20%;background:#B8BFCA"></i><i style="width:30%;background:#B42318"></i></div>
<div class="leg"><span style="--c:#1B7A43">{lg[0]}</span><span style="--c:#B8BFCA">{lg[1]}</span><span style="--c:#B42318">{lg[2]}</span></div>
<h2>{x["brand_h"]} <small>{x["brand_n"]}</small></h2>
{"".join(card(c) for c in x["brand"])}
<h2>{x["comp_h"]} <small>{x["comp_n"]}</small></h2>
{comp}
<div class="foot">{"".join(f"<p>{p}</p>" for p in x["foot"])}</div>
<script>window.__pageFoot={{text:{E(x["page_foot"])!r},page:{x["page_word"]!r},title:{x["doc_title"]!r}}}</script>
</body></html>'''


os.makedirs(OUT, exist_ok=True)
for k, x in L.items():
    with open(os.path.join(OUT, f"report-{k}.html"), "w", encoding="utf-8") as f:
        f.write(build(x))
    print("wrote", f"report-{k}.html")
